// Get all shipments
export function getAllShipments(): Shipment[] {
  return SHIPMENTS_DATABASE;
}

// Get shipments by client ID
export function getShipmentsByClientId(clientId: string): Shipment[] {
  // Try direct match first
  let filtered = SHIPMENTS_DATABASE.filter(s => s.clientId === clientId);
  
  // If no results and it's a demo account, map to c1
  if (filtered.length === 0 && clientId === 'demo-client-1') {
    filtered = SHIPMENTS_DATABASE.filter(s => s.clientId === 'c1');
  }
  
  return filtered;
}

// Get single shipment by ID
export function getShipmentById(shipmentId: string): Shipment | undefined {
  return SHIPMENTS_DATABASE.find(s => s.id === shipmentId);
}
